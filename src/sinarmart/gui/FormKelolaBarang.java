    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {                                          
        String kode = txtKode.getText().trim();
        String nama = txtNama.getText().trim();
        String kategori = (String) cbKategori.getSelectedItem();
        String satuan = txtSatuan.getText().trim();

        if (kode.isEmpty() || nama.isEmpty() || satuan.isEmpty() || txtBeli.getText().isEmpty() || txtJual.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Harap lengkapi semua kolom input barang!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double beli = Double.parseDouble(txtBeli.getText().trim());
            double jual = Double.parseDouble(txtJual.getText().trim());
            int stok = (Integer) spStok.getValue();
            int min = (Integer) spStokMin.getValue();

            // Aturan Bisnis 1: Harga jual tidak boleh lebih rendah dari harga beli
            if (jual < beli) {
                JOptionPane.showMessageDialog(this, 
                    "Aturan Bisnis 1: Harga jual (Rp " + String.format("%,.0f", jual) + 
                    ") tidak boleh lebih rendah dari harga beli (Rp " + String.format("%,.0f", beli) + ")!", 
                    "Penetapan Harga Ditolak", 
                    JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            Barang existing = service.getBarang(kode);
            boolean aktif = (existing != null) ? existing.isAktif() : true;

            Barang b = new Barang(kode, nama, kategori, satuan, beli, jual, stok, min, aktif);
            service.simpanBarang(b);

            JOptionPane.showMessageDialog(this, "Data barang '" + nama + "' berhasil disimpan!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
            muatDataBarang("");
            resetForm();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Harga beli dan harga jual harus berupa angka valid!", "Kesalahan Input", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }                                         

    private void btnUbahStatusActionPerformed(java.awt.event.ActionEvent evt) {                                              
        int row = tblBarang.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih salah satu barang di tabel untuk diubah statusnya!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String kode = (String) modelTabel.getValueAt(row, 0);
        Barang b = service.getBarang(kode);
        if (b != null) {
            // Aturan Bisnis P1: Barang tidak dihapus melainkan dinonaktifkan
            b.setAktif(!b.isAktif());
            service.simpanBarang(b);
            String st = b.isAktif() ? "Diaktifkan" : "Dinonaktifkan";
            JOptionPane.showMessageDialog(this, "Barang " + b.getNamaBarang() + " berhasil " + st + "!", "Status Barang", JOptionPane.INFORMATION_MESSAGE);
            muatDataBarang("");
        }
    }                                             

    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {                                         
        resetForm();
    }                                        

    private void tblBarangMouseClicked(java.awt.event.MouseEvent evt) {                                       
        int row = tblBarang.getSelectedRow();
        if (row >= 0) {
            String kode = (String) modelTabel.getValueAt(row, 0);
            Barang b = service.getBarang(kode);
            if (b != null) {
                txtKode.setText(b.getKodeBarang());
                txtKode.setEditable(false);
                txtNama.setText(b.getNamaBarang());
                cbKategori.setSelectedItem(b.getKategori());
                txtSatuan.setText(b.getSatuan());
                txtBeli.setText(String.format("%.0f", b.getHargaBeli()));
                txtJual.setText(String.format("%.0f", b.getHargaJual()));
                spStok.setValue(b.getStok());
                spStokMin.setValue(b.getStokMin());
            }
        }
    }                                      

