    private void muatDataBarang(String keyword) {
        modelTabel.setRowCount(0);
        List<Barang> list = service.cariBarang(keyword);
        for (Barang b : list) {
            String status = b.isAktif() ? "Aktif" : "Non-Aktif";
            String stokStr = String.valueOf(b.getStok());
            if (b.isDibawahStokMin()) {
                stokStr += " (Menipis < " + b.getStokMin() + ")";
            }

            modelTabel.addRow(new Object[]{
                b.getKodeBarang(),
                b.getNamaBarang(),
                b.getKategori(),
                b.getSatuan(),
                String.format("%,.0f", b.getHargaBeli()),
                String.format("%,.0f", b.getHargaJual()),
                stokStr,
                status
            });
        }
    }

