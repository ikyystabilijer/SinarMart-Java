    private void btnCetakStrukActionPerformed(java.awt.event.ActionEvent evt) {                                              
        Transaksi tToPrint = (transaksiTerakhirLunas != null) ? transaksiTerakhirLunas : 
                             (transaksiAktif != null && transaksiAktif.isLunas()) ? transaksiAktif : null;

        if (tToPrint == null) {
            JOptionPane.showMessageDialog(this, "Belum ada transaksi lunas untuk dicetak struknya!", "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        Struk struk = new Struk(tToPrint);
        String teksStruk = struk.cetak();

        // Tampilkan dialog pratinjau struk
        JTextArea ta = new JTextArea(teksStruk);
        ta.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 12));
        ta.setEditable(false);
        JScrollPane sp = new JScrollPane(ta);
        sp.setPreferredSize(new java.awt.Dimension(360, 420));

        int option = JOptionPane.showOptionDialog(
            this,
            sp,
            "Pratinjau Struk: " + tToPrint.getNoTransaksi(),
            JOptionPane.YES_NO_OPTION,
            JOptionPane.PLAIN_MESSAGE,
            null,
            new Object[]{"Simpan Berkas .txt", "Tutup"},
            "Simpan Berkas .txt"
        );

        if (option == 0) {
            try {
                File saved = struk.simpanKeFile(System.getProperty("user.dir") + File.separator + "struk");
                JOptionPane.showMessageDialog(this, "Struk berhasil disimpan di:\n" + saved.getAbsolutePath(), "Struk Tersimpan", JOptionPane.INFORMATION_MESSAGE);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Gagal menyimpan berkas struk: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }                                             

