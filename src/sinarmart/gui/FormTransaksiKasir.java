    private void btnTambahKeranjangActionPerformed(java.awt.event.ActionEvent evt) {                                                   
        int row = tblKatalog.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih salah satu barang di tabel katalog terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String kode = (String) modelKatalog.getValueAt(row, 0);
        Barang b = service.getBarang(kode);
        if (b == null) {
            JOptionPane.showMessageDialog(this, "Data barang tidak ditemukan!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int qty = (Integer) spJumlah.getValue();
        try {
            // Aturan Bisnis 2: Transaksi tidak dapat disimpan jika stok barang tidak mencukupi
            transaksiAktif.tambahItem(b, qty);
            updateTampilanKeranjang();
            spJumlah.setValue(1);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validasi Stok Kurang", JOptionPane.WARNING_MESSAGE);
        }
    }                                                  

    private void btnUbahQtyActionPerformed(java.awt.event.ActionEvent evt) {                                           
        int row = tblKeranjang.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih item di keranjang yang ingin diubah!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String input = JOptionPane.showInputDialog(this, "Masukkan jumlah baru:", modelKeranjang.getValueAt(row, 3));
        if (input == null || input.trim().isEmpty()) return;

        try {
            int newQty = Integer.parseInt(input.trim());
            transaksiAktif.ubahJumlahItem(row, newQty);
            updateTampilanKeranjang();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Jumlah harus berupa angka valid!", "Kesalahan Input", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Kesalahan", JOptionPane.WARNING_MESSAGE);
        }
    }                                          

    private void btnHapusItemActionPerformed(java.awt.event.ActionEvent evt) {                                             
        int row = tblKeranjang.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih item belanja yang ingin dibatalkan!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        transaksiAktif.hapusItem(row);
        updateTampilanKeranjang();
    }                                            

