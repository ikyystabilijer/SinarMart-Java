    private void inisialisasiAplikasi() {
        lblInfoKasir.setText("Kasir: " + namaKasir);
        if (service.getShiftAktif() != null) {
            lblInfoShift.setText("Shift: " + service.getShiftAktif().getIdShift());
        } else {
            lblInfoShift.setText("Shift: Belum Buka");
        }

        modelKatalog = (DefaultTableModel) tblKatalog.getModel();
        modelKeranjang = (DefaultTableModel) tblKeranjang.getModel();

        muatKatalogBarang("");
        mulaiTransaksiBaru();
        updateStatusJaringan();
    }

    public void updateStatusJaringan() {
        boolean online = service.getServer().isOnline();
        if (online) {
            lblStatusJaringan.setText("● STATUS: ONLINE");
            lblStatusJaringan.setForeground(new Color(0, 153, 51));
            btnToggleJaringan.setText("Simulasi Putus Jaringan");
            btnToggleJaringan.setBackground(new Color(255, 235, 235));
        } else {
            lblStatusJaringan.setText("● STATUS: OFFLINE");
            lblStatusJaringan.setForeground(new Color(204, 0, 0));
            btnToggleJaringan.setText("Hubungkan Jaringan");
            btnToggleJaringan.setBackground(new Color(230, 255, 230));
        }
    }

    public void mulaiTransaksiBaru() {
        try {
            this.transaksiAktif = service.buatTransaksiBaru(namaKasir);
            lblNoTrx.setText("TRX: " + transaksiAktif.getNoTransaksi());
            updateTampilanKeranjang();
        } catch (IllegalStateException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Shift Belum Dibuka", JOptionPane.WARNING_MESSAGE);
            new FormBukaShift(namaKasir).setVisible(true);
            this.dispose();
        }
    }

    public void muatKatalogBarang(String keyword) {
        modelKatalog.setRowCount(0);
        List<Barang> list = service.cariBarang(keyword);
        for (Barang b : list) {
            if (b.isAktif()) {
                String stokDisplay = String.valueOf(b.getStok());
                if (b.isDibawahStokMin()) {
                    stokDisplay += " (MENIPIS!)";
                }
                modelKatalog.addRow(new Object[]{
                    b.getKodeBarang(),
                    b.getNamaBarang(),
                    String.format("%,.0f", b.getHargaJual()),
                    stokDisplay
                });
            }
        }
    }

    private void updateTampilanKeranjang() {
        modelKeranjang.setRowCount(0);
        if (transaksiAktif == null) return;

        int no = 1;
        for (DetailTransaksi d : transaksiAktif.getItems()) {
            modelKeranjang.addRow(new Object[]{
                no++,
                d.getBarang().getKodeBarang(),
                d.getBarang().getNamaBarang(),
                d.getJumlah(),
                String.format("%,.0f", d.getHargaSatuan()),
                String.format("%,.0f", d.getSubtotal())
            });
        }

        lblSubtotalVal.setText("Rp " + String.format("%,.0f", transaksiAktif.getSubtotal()));
        if (transaksiAktif.getDiskonPersen() > 0) {
            lblDiskonVal.setText("-Rp " + String.format("%,.0f", transaksiAktif.getNominalDiskon()) + " (5%)");
        } else {
            lblDiskonVal.setText("Rp 0 (0%)");
        }
        lblTotalAkhirVal.setText("Rp " + String.format("%,.0f", transaksiAktif.getTotalAkhir()));
    }

    public void onTransaksiLunas(Transaksi t) {
        this.transaksiTerakhirLunas = t;
        muatKatalogBarang("");
        mulaiTransaksiBaru();
    }

