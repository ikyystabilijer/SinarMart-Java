    private void btnToggleJaringanActionPerformed(java.awt.event.ActionEvent evt) {                                                  
        boolean currentOnline = service.getServer().isOnline();
        service.getServer().setOnline(!currentOnline);
        updateStatusJaringan();

        if (!currentOnline) {
            JOptionPane.showMessageDialog(this, "Koneksi jaringan server kembali TERHUBUNG (ONLINE).\nAntrean offline siap disinkronkan!", "Status Jaringan", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Koneksi jaringan server DIPUTUS (OFFLINE).\nTransaksi selanjutnya akan disimpan ke antrean lokal!", "Status Jaringan", JOptionPane.WARNING_MESSAGE);
        }
    }                                                 

