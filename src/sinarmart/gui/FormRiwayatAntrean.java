    public void muatData() {
        modelTabel.setRowCount(0);
        List<Transaksi> list = antreanKirim.getDaftarTransaksi();
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy HH:mm");

        for (Transaksi t : list) {
            String metode = (t.getPembayaran() != null) ? t.getPembayaran().getMetode() : "Tunai";
            String status = t.getStatusKirim();
            modelTabel.addRow(new Object[]{
                t.getNoTransaksi(),
                sdf.format(t.getTanggal()),
                t.getKasir(),
                "Rp " + String.format("%,.0f", t.getTotalAkhir()),
                metode,
                status
            });
        }

        boolean online = service.getServer().isOnline();
        if (online) {
            lblStatusServer.setText("Server: ONLINE");
            lblStatusServer.setForeground(new Color(0, 153, 51));
        } else {
            lblStatusServer.setText("Server: OFFLINE");
            lblStatusServer.setForeground(new Color(204, 0, 0));
        }

        int pending = antreanKirim.getJumlahPending();
        lblInfoPending.setText(pending + " Menunggu Kirim");
        if (pending > 0) {
            lblInfoPending.setForeground(new Color(204, 85, 0));
        } else {
            lblInfoPending.setForeground(new Color(0, 153, 51));
        }
    }

