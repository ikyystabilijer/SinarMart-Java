    private void btnSyncSekarangActionPerformed(java.awt.event.ActionEvent evt) {                                                
        if (!service.getServer().isOnline()) {
            JOptionPane.showMessageDialog(this, 
                "Server sedang OFFLINE!\nSilakan aktifkan koneksi simulasi terlebih dahulu sebelum sinkronisasi.", 
                "Koneksi Offline", 
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int synced = antreanKirim.sinkronkan(service.getServer());
        muatData();

        JOptionPane.showMessageDialog(
            this,
            "Proses sinkronisasi selesai.\n" +
            "Jumlah transaksi disinkronkan: " + synced + "\n" +
            "Mekanisme Idempotensi: Kunci unik transaksi berhasil mencegah duplikasi pencatatan (Bukti 1 & 2 teratasi).",
            "Sinkronisasi Berhasil",
            JOptionPane.INFORMATION_MESSAGE
        );
    }                                               

    private void btnLihatStrukActionPerformed(java.awt.event.ActionEvent evt) {                                              
        int row = tblRiwayat.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih salah satu transaksi dari tabel terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String noTrx = (String) modelTabel.getValueAt(row, 0);
        List<Transaksi> list = antreanKirim.getDaftarTransaksi();
        Transaksi target = null;
        for (Transaksi t : list) {
            if (t.getNoTransaksi().equals(noTrx)) {
                target = t;
                break;
            }
        }

        if (target != null) {
            Struk s = new Struk(target);
            JTextArea ta = new JTextArea(s.cetak());
            ta.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 12));
            ta.setEditable(false);
            JScrollPane sp = new JScrollPane(ta);
            sp.setPreferredSize(new java.awt.Dimension(360, 420));
            JOptionPane.showMessageDialog(this, sp, "Struk: " + target.getNoTransaksi(), JOptionPane.PLAIN_MESSAGE);
        }
    }                                             

