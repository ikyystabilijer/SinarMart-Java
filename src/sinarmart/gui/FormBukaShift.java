    private void btnBukaShiftActionPerformed(java.awt.event.ActionEvent evt) {                                             
        try {
            double modal = Double.parseDouble(txtModalAwal.getText().trim());
            if (modal < 0) {
                JOptionPane.showMessageDialog(this, "Modal awal tidak boleh negatif!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Aturan Bisnis 9: Satu kasir hanya boleh memiliki satu shift terbuka pada satu waktu
            Shift s = service.bukaShift(namaKasir, modal);
            JOptionPane.showMessageDialog(this, "Shift kasir berhasil dibuka dengan ID: " + s.getIdShift(), "Sukses", JOptionPane.INFORMATION_MESSAGE);

            new FormTransaksiKasir(namaKasir).setVisible(true);
            this.dispose();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Nominal modal awal harus berupa angka valid!", "Kesalahan Input", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalStateException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Aturan Bisnis (Shift Ganda)", JOptionPane.WARNING_MESSAGE);
        }
    }                                            

