    private void txtInputUtamaKeyReleased(java.awt.event.KeyEvent evt) {                                          
        String metode = (String) cbMetode.getSelectedItem();
        if ("Tunai".equalsIgnoreCase(metode)) {
            try {
                String val = txtInputUtama.getText().trim();
                if (val.isEmpty()) {
                    txtInputKedua.setText("0");
                    return;
                }
                double uang = Double.parseDouble(val);
                double selisih = uang - transaksi.getTotalAkhir();
                if (selisih >= 0) {
                    txtInputKedua.setText(String.format("%,.0f", selisih));
                    txtInputKedua.setForeground(new java.awt.Color(0, 153, 0));
                } else {
                    txtInputKedua.setText("Kurang: Rp " + String.format("%,.0f", Math.abs(selisih)));
                    txtInputKedua.setForeground(new java.awt.Color(204, 0, 0));
                }
            } catch (NumberFormatException ignore) {
                txtInputKedua.setText("Input angka tidak valid");
                txtInputKedua.setForeground(new java.awt.Color(204, 0, 0));
            }
        }
    }                                         

    private void btnKonfirmasiLunasActionPerformed(java.awt.event.ActionEvent evt) {                                                   
        if (transaksi == null) return;

        String metode = (String) cbMetode.getSelectedItem();
        Pembayaran p;

        try {
            if ("Tunai".equalsIgnoreCase(metode)) {
                String val = txtInputUtama.getText().trim();
                if (val.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Masukkan nominal uang tunai yang diterima!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                    return;
                }
                double uangDiterima = Double.parseDouble(val);

                // Polimorfisme & Validasi Aturan 4 (Tolak jika uang kurang)
                p = new PembayaranTunai(uangDiterima);
            } else {
                String noRef = txtInputUtama.getText().trim();
                p = new PembayaranNonTunai(metode, noRef);
            }

            // Selesaikan transaksi di Service
            service.selesaikanTransaksi(transaksi, p);

            // Cetak dan simpan struk otomatis
            Struk struk = new Struk(transaksi);
            try {
                File dirStruk = new File(System.getProperty("user.dir") + File.separator + "struk");
                File savedStruk = struk.simpanKeFile(dirStruk.getAbsolutePath());
                System.out.println("[STRUK] Tersimpan di: " + savedStruk.getAbsolutePath());
            } catch (Exception ex) {
                System.err.println("[STRUK WARNING] " + ex.getMessage());
            }

            String pesan = "Pembayaran Berhasil Dicatat!\n" +
                           "No Transaksi: " + transaksi.getNoTransaksi() + "\n" +
                           "Total: Rp " + String.format("%,.0f", transaksi.getTotalAkhir()) + "\n" +
                           "Status Kirim: " + (transaksi.getStatusKirim().equals("TERKIRIM") ? "Terkirim ke Server" : "Tersimpan di Antrean Offline");

            if (p instanceof PembayaranTunai) {
                pesan += "\nKembalian: Rp " + String.format("%,.0f", ((PembayaranTunai) p).getKembalian());
            }

            JOptionPane.showMessageDialog(this, pesan, "Transaksi Lunas", JOptionPane.INFORMATION_MESSAGE);

            if (parentForm != null) {
                parentForm.onTransaksiLunas(transaksi);
            }
            this.dispose();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Nominal pembayaran harus berupa angka valid!", "Kesalahan Input", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException ex) {
            // Menangkap penolakan uang tunai kurang atau stok kurang
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Validasi Pembayaran Ditolak", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Gagal memproses pembayaran: " + ex.getMessage(), "Kesalahan", JOptionPane.ERROR_MESSAGE);
        }
    }                                                  

