    private void txtUangFisikKeyReleased(java.awt.event.KeyEvent evt) {                                         
        try {
            String val = txtUangFisik.getText().trim();
            if (val.isEmpty()) {
                lblSelisihVal.setText("Rp 0");
                return;
            }
            double fisik = Double.parseDouble(val);
            double selisih = fisik - shift.hitungUangSeharusnya();

            if (selisih > 0) {
                lblSelisihVal.setText("+Rp " + String.format("%,.0f", selisih) + " (Lebih / Surplus)");
                lblSelisihVal.setForeground(new Color(0, 153, 51));
            } else if (selisih < 0) {
                lblSelisihVal.setText("-Rp " + String.format("%,.0f", Math.abs(selisih)) + " (Kurang / Defisit)");
                lblSelisihVal.setForeground(new Color(204, 0, 0));
            } else {
                lblSelisihVal.setText("Rp 0 (Sesuai / Seimbang)");
                lblSelisihVal.setForeground(new Color(0, 102, 204));
            }
        } catch (NumberFormatException ignore) {
            lblSelisihVal.setText("Input angka tidak valid");
            lblSelisihVal.setForeground(new Color(204, 0, 0));
        }
    }                                        

    private void btnKunciShiftActionPerformed(java.awt.event.ActionEvent evt) {                                              
        try {
            String val = txtUangFisik.getText().trim();
            if (val.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Silakan hitung dan masukkan nominal uang fisik di laci!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                return;
            }

            double fisik = Double.parseDouble(val);
            int confirm = JOptionPane.showConfirmDialog(
                this,
                "Apakah Anda yakin ingin MENUTUP dan MENGUNCI shift ini?\nData rekap tidak dapat diubah kembali setelah ditutup.",
                "Konfirmasi Tutup Shift",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
            );

            if (confirm != JOptionPane.YES_OPTION) return;

            // Tutup shift di Service
            service.tutupShift(fisik);

            // Simpan laporan rekap shift ke disk
            simpanBerkasRekapShift(shift);

            JOptionPane.showMessageDialog(
                this,
                "Shift " + shift.getIdShift() + " BERHASIL DITUTUP!\n" +
                "Kasir: " + shift.getKasir() + "\n" +
                "Modal Awal: Rp " + String.format("%,.0f", shift.getModalAwal()) + "\n" +
                "Penjualan Tunai: Rp " + String.format("%,.0f", shift.getTotalTunai()) + "\n" +
                "Uang Fisik di Laci: Rp " + String.format("%,.0f", shift.getUangFisikLaci()) + "\n" +
                "Selisih Kas: Rp " + String.format("%,.0f", shift.getSelisih()),
                "Shift Selesai & Terkunci",
                JOptionPane.INFORMATION_MESSAGE
            );

            if (parentForm != null) {
                parentForm.dispose();
            }
            new FormLogin().setVisible(true);
            this.dispose();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Uang fisik harus berupa angka valid!", "Kesalahan Input", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Gagal menutup shift: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }                                             

    private void simpanBerkasRekapShift(Shift s) {
        try {
            File dir = new File(System.getProperty("user.dir") + File.separator + "laporan_shift");
            if (!dir.exists()) dir.mkdirs();

            SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy HH:mm:ss");
            File file = new File(dir, "REKAP_" + s.getIdShift() + ".txt");

            try (FileWriter fw = new FileWriter(file)) {
                fw.write("====================================\n");
                fw.write("    REKAP TUTUP SHIFT KASIR\n");
                fw.write("        TOKO SINAR MART\n");
                fw.write("====================================\n");
                fw.write("ID Shift    : " + s.getIdShift() + "\n");
                fw.write("Kasir       : " + s.getKasir() + "\n");
                fw.write("Waktu Buka  : " + sdf.format(s.getWaktuBuka()) + "\n");
                fw.write("Waktu Tutup : " + sdf.format(s.getWaktuTutup()) + "\n");
                fw.write("------------------------------------\n");
                fw.write(String.format("Modal Awal          : Rp %,.0f\n", s.getModalAwal()));
                fw.write(String.format("Penjualan Tunai     : Rp %,.0f\n", s.getTotalTunai()));
                fw.write(String.format("Penjualan Non-Tunai : Rp %,.0f\n", s.getTotalNonTunai()));
                fw.write(String.format("Total Transaksi     : %d\n", s.getTotalTransaksi()));
                fw.write(String.format("Uang Seharusnya     : Rp %,.0f\n", s.hitungUangSeharusnya()));
                fw.write(String.format("Uang Fisik Laci     : Rp %,.0f\n", s.getUangFisikLaci()));
                fw.write(String.format("Selisih             : Rp %,.0f\n", s.getSelisih()));
                fw.write("Status Shift        : TERKUNCI (CLOSED)\n");
                fw.write("====================================\n");
            }
        } catch (Exception ignore) {}
    }

