    private void inisialisasi() {
        modelTrx = (DefaultTableModel) tblTransaksiLaporan.getModel();
        modelStok = (DefaultTableModel) tblStokMenipis.getModel();
        muatLaporan();
    }

    public void muatLaporan() {
        modelTrx.setRowCount(0);
        modelStok.setRowCount(0);

        List<Transaksi> listTrx = service.getAntreanKirim().getDaftarTransaksi();
        double totalOmzet = 0.0;
        double totalModalBarangTerjual = 0.0;
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy HH:mm");

        for (Transaksi t : listTrx) {
            totalOmzet += t.getTotalAkhir();
            for (DetailTransaksi d : t.getItems()) {
                totalModalBarangTerjual += (d.getBarang().getHargaBeli() * d.getJumlah());
            }

            modelTrx.addRow(new Object[]{
                t.getNoTransaksi(),
                sdf.format(t.getTanggal()),
                t.getKasir(),
                String.format("%,.0f", t.getSubtotal()),
                String.format("%,.0f", t.getNominalDiskon()),
                String.format("%,.0f", t.getTotalAkhir())
            });
        }

        double estimasiLabaKotor = totalOmzet - totalModalBarangTerjual;
        lblOmzetVal.setText("Rp " + String.format("%,.0f", totalOmzet));
        lblLabaVal.setText("Rp " + String.format("%,.0f", estimasiLabaKotor));
        lblTrxCountVal.setText(listTrx.size() + " Transaksi");

        // Muat barang stok menipis
        List<Barang> listMenipis = service.getBarangStokMenipis();
        lblStokPeringatanVal.setText(listMenipis.size() + " Produk");

        for (Barang b : listMenipis) {
            modelStok.addRow(new Object[]{
                b.getKodeBarang(),
                b.getNamaBarang(),
                b.getKategori(),
                b.getStok(),
                b.getStokMin()
            });
        }
    }

